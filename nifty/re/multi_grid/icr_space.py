"""The multigrid factor of a correlated field: geometry and the settings of
its :class:`~nifty.re.multi_grid.ICRGP` model, which the correlated field
builds at `finalize`."""

from typing import Optional, Tuple

import jax
import jax.numpy as jnp
import numpy as np

from ..correlated_field import KernelSpace
from .grid import Grid
from .icr_gp import _distances, _window_coordinates
from .kernel import ICRKernel

__all__ = ["ICRSpace"]


class ICRSpace(KernelSpace):
    """Multigrid factor generated by iterative charted refinement
    (:class:`~nifty.re.multi_grid.ICRGP`, built by the correlated field).

    Parameters
    ----------
    grid : nifty.re.multi_grid.Grid
        The multigrid; the field lives on its finest level, the excitations
        are the levels one after the other (plus the zero mode).
    r_min, r_max, n_bins : float, float, int
        Covariance table (see :class:`~nifty.re.correlated_field.KernelSpace`).
        By default `r_max` is 1.05 times the diagonal of the bounding box of
        the points of all levels (which bounds every window distance) and
        `r_min` half the smallest distance in the window of one finest-level
        cell; the ICRGP checks the windows it actually uses against the table
        and warns if they reach beyond it.
        The covariance is interpolated linearly between the (logarithmically
        spaced) radial bins; too few bins per decade make the interpolated
        window covariances indefinite and the Cholesky factorization fails
        with NaNs (for a steep spectrum 35 bins per decade were indefinite and
        135 fine; keep at least 100 per decade of ``r_max / r_min``).
    window_size : tuple or None
        Coarse window of the refinement at each level (grid default: 3 along
        every axis).
    compress : dict or None
        Tolerances of the window compression (``rtol``, ``atol``,
        ``buffer_size``, ``chunk_size``), see
        :func:`~nifty.re.multi_grid.icr_gp.compress_indices`; ``None`` keeps
        every window.
    chunk_size : int
        Number of cells refined at once.
    kernel_chunk : int
        Number of unique windows whose refinement matrices are built at once.
    cholesky_jitter : float
        Added to the diagonal of every window covariance relative to its mean
        before the Cholesky factorization (windows at a grid boundary contain
        coincident points).
    jitter : float
        Relative inflation of the covariance at zero distance.
    radial_bins, k_bins : arrays, optional
        Explicit bins in place of `r_min`, `r_max` and `n_bins`.
    """

    def __init__(
        self,
        grid: Grid,
        *,
        r_min=None,
        r_max=None,
        n_bins=1024,
        window_size=None,
        compress: Optional[dict] = dict(rtol=1e-5, atol=1e-10, buffer_size=10_000),
        chunk_size=2**16,
        kernel_chunk=4096,
        cholesky_jitter=1e-6,
        jitter=1e-6,
        radial_bins=None,
        k_bins=None,
    ):
        self.multigrid = grid
        self._window_size = window_size
        self._compress = None if not compress else tuple(sorted(dict(compress).items()))
        self.chunk_size = int(chunk_size)
        self.kernel_chunk = int(kernel_chunk)
        self.cholesky_jitter = float(cholesky_jitter)
        self._level_shapes = tuple(tuple(int(s) for s in grid.at(l).shape) for l in range(grid.depth + 1))
        sizes = [int(np.prod(s)) for s in self._level_shapes]
        g0 = grid.at(0)
        dim = int(g0.index2coord(np.zeros((g0.ndim, 1), dtype=np.int64)).shape[0])
        if r_max is None and radial_bins is None:
            # the diagonal of the bounding box of the points of all levels (padded
            # coarse levels included) bounds every window distance
            lo, hi = None, None
            for lvl in range(grid.depth + 1):
                g = grid.at(lvl)
                idx = jnp.stack(jnp.unravel_index(jnp.arange(int(np.prod(g.shape))), tuple(int(s) for s in g.shape)))
                c = jax.jit(lambda i, g=g: (jnp.min(g.index2coord(i), axis=1), jnp.max(g.index2coord(i), axis=1)))(idx)
                lo = c[0] if lo is None else jnp.minimum(lo, c[0])
                hi = c[1] if hi is None else jnp.maximum(hi, c[1])
            r_max = 1.05 * float(jnp.linalg.norm(hi - lo))
        if r_min is None and (radial_bins is None or k_bins is None):
            # half the smallest distance in the window of one finest-level cell
            kernel = ICRKernel(grid, None, window_size=window_size)
            lvl = grid.depth - 1
            cell = np.asarray(grid.at(lvl).refined_indices()).reshape(grid.at(lvl).ndim, -1)[:, :1]
            d = np.asarray(jax.jit(lambda i: _distances(_window_coordinates(kernel, i, lvl)))(jnp.asarray(cell)))
            r_min = 0.5 * float(d[d > 0].min())
        super().__init__(
            self._level_shapes[-1],
            dim,
            n_points=sum(sizes),
            r_min=r_min,
            r_max=r_max,
            n_bins=n_bins,
            jitter=jitter,
            radial_bins=radial_bins,
            k_bins=k_bins,
        )

    @property
    def compress(self) -> Optional[dict]:
        """Settings of the window compression (``None``: no compression)."""
        return None if self._compress is None else dict(self._compress)

    @property
    def window_size(self):
        return self._window_size

    @property
    def depth(self) -> int:
        return self.multigrid.depth

    @property
    def level_shapes(self) -> Tuple[Tuple[int, ...], ...]:
        return self._level_shapes

    @property
    def gp_kwargs(self) -> dict:
        return dict(
            window_size=self._window_size,
            compress=self.compress,
            chunk_size=self.chunk_size,
            kernel_chunk=self.kernel_chunk,
            cholesky_jitter=self.cholesky_jitter,
        )
